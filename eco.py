# ГОЛОВНИЙ ЕКРАН
st.title("🌱 Інтерактивний Еко-Помічник")

if "messages" not in st.session_state:
    st.session_state.messages = []

# Оновлення при виборі готової теми
if "current_topic" not in st.session_state or st.session_state.current_topic != topic:
    if topic in eco_data:
        st.session_state.current_topic = topic
        resp = eco_data[topic]
        st.session_state.messages.append({"role": "assistant", "content": resp["text"], "image": resp["img"]})
    else:
        st.session_state.current_topic = topic
        welcome = "Я твій еко-помічник! Напиши мені питання нижче (наприклад, про воду чи ліс), і я дам розгорнуту інструкцію."
        st.session_state.messages.append({"role": "assistant", "content": welcome, "image": "https://images.unsplash.com/photo-1485827404703-89b55fcc595e?q=80&w=600"})

# Відображення
for msg in st.session_state.messages:
    with st.chat_message(msg["role"]):
        st.markdown(msg["content"])
        if "image" in msg:
            st.image(msg["image"], width=600)

# РОЗУМНИЙ ЧАТ
if prompt := st.chat_input("Напишіть своє питання тут..."):
    st.session_state.messages.append({"role": "user", "content": prompt})
    with st.chat_message("user"):
        st.markdown(prompt)
    
    with st.chat_message("assistant"):
        p_low = prompt.lower()
        # Пошук ключових слів для довгих відповідей
        if "вод" in p_low:
            data = eco_data["Як очистити воду?"]
            ans, img = data["text"], data["img"]
        elif "смітт" in p_low or "сортув" in p_low:
            data = eco_data["Як сортувати сміття?"]
            ans, img = data["text"], data["img"]
        elif "ліс" in p_low or "дерев" in p_low:
            data = eco_data["Захист лісів"]
            ans, img = data["text"], data["img"]
        else:
            ans = f"Дякую за питання про '{prompt}'! Це дуже важлива тема для нашої планети. Я раджу тобі також переглянути розділ про сортування сміття, щоб дізнатися більше про допомогу довкіллю."
            img = "https://images.unsplash.com/photo-1451187580459-43490279c0fa?q=80&w=600"
        
        st.markdown(ans)
        st.image(img, width=600)
        st.session_state.messages.append({"role": "assistant", "content": ans, "image": img})
